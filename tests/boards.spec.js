test('S13 — Edit Board : Doing renommé In Progress (statut des 6 tâches), Review ajoutée, Done retirée avec ses 7 tâches ; Cancel ne change rien', async ({ page }) => {
  await open(page, 1440)
  await boardMenu(page).click()
  await button(page, 'Edit Board').click()
  let d = dialog(page, 'Edit Board')
  await field(d, 'Board Name').fill('Platform Launch v2')
  await page.keyboard.press('Escape')
  await expect(title(page)).toHaveText('Platform Launch')
  await boardMenu(page).click()
  await button(page, 'Edit Board').click()
  d = dialog(page, 'Edit Board')
  const cols = group(d, 'Board Columns')
  await expect(field(d, 'Board Name')).toHaveValue('Platform Launch')
  await expect(field(cols, 'Column 3')).toHaveValue('Done')
  await field(cols, 'Column 2').fill('In Progress')
  await button(cols, 'Remove column 3').click()
  await button(d, '+ Add New Column').click()
  await field(cols, 'Column 3').fill('Review')
  await button(d, 'Save Changes').click()
  await expect(d).toBeHidden()
  const doing = board('Platform Launch').columns[1].tasks.map((t) => t.title)
  expect(await titlesIn(page, 'In Progress')).toEqual(doing)
  await expect(columnHeading(page, 'Review')).toHaveText('Review (0)', { ignoreCase: true })
  await expect(column(page, 'Done')).toHaveCount(0)
  const saved = (await stored(page)).boards[0]
  expect(saved.columns.map((c) => c.name)).toEqual(['Todo', 'In Progress', 'Review'])
  expect(saved.columns[1].tasks.every((t) => t.status === 'In Progress')).toBe(true)
})

