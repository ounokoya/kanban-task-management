import { test, expect } from '@playwright/test'
import { open, DATA, board, subtaskText, stored, nav, main, title, boardLink, column, columnHeading, cardsIn, titlesIn, addTask, boardMenu, button, dialog, alert, group, field, status, themeSwitch, style, sameColor } from './helpers.js'

// Spec §2, §3.1 à §3.3, §3.6 à §3.8 et §8 — S7 à S16 : tableaux, colonnes, barre latérale (parcours complets)

const COLORS = ['#49c4e5', '#8471f2', '#67e2ae']

test('S7 — premier chargement : All boards (3), Platform Launch ouvert, chaque colonne (titre, compteur, couleur) et chaque carte dans l\'ordre', async ({ page }) => {
  await open(page, 1440)
  await expect(nav(page).getByText(/^All boards \(3\)$/i)).toBeVisible()
  for (const b of DATA.boards) await expect(boardLink(page, b.name)).toBeVisible()
  await expect(boardLink(page, 'Platform Launch')).toHaveAttribute('aria-current', 'page')
  await expect(title(page)).toHaveText('Platform Launch')
  await expect(page).toHaveTitle('Platform Launch | Kanban task management')
  for (const [i, col] of board('Platform Launch').columns.entries()) {
    await expect(columnHeading(page, col.name)).toHaveText(`${col.name} (${col.tasks.length})`, { ignoreCase: true })
    const dot = await columnHeading(page, col.name).evaluate((h) => { const d = [...h.parentElement.querySelectorAll('*')].find((n) => n.offsetWidth === 15 && n.offsetHeight === 15); return d && getComputedStyle(d).backgroundColor })
    expect.soft(await sameColor(page, dot || 'transparent', COLORS[i]), `point de ${col.name}`).toBe(true)
    expect(await titlesIn(page, col.name)).toEqual(col.tasks.map((t) => t.title))
    for (const [j, task] of col.tasks.entries()) await expect(cardsIn(page, col.name).nth(j)).toContainText(subtaskText(task))
  }
})

test('S8 — chaque tableau : adresse, titre de la page, h1, colonnes, annonce ; retour et rechargement ; adresse inconnue', async ({ page }) => {
  await open(page, 1440)
  for (const [b, slug] of [['Marketing Plan', 'marketing-plan'], ['Roadmap', 'roadmap'], ['Platform Launch', 'platform-launch']]) {
    await boardLink(page, b).click()
    await expect(page).toHaveURL(new RegExp(`#/board/${slug}$`))
    await expect(title(page)).toHaveText(b)
    await expect(page).toHaveTitle(`${b} | Kanban task management`)
    await expect(boardLink(page, b)).toHaveAttribute('aria-current', 'page')
    for (const col of board(b).columns) expect(await titlesIn(page, col.name)).toEqual(col.tasks.map((t) => t.title))
    await expect(status(page)).toContainText(b)
  }
  await page.goBack()
  await expect(title(page)).toHaveText('Roadmap')
  await page.reload()
  await expect(title(page)).toHaveText('Roadmap')
  await page.goto('./#/board/nothing-here')
  await expect(title(page)).toHaveText('Platform Launch')
})

